public class Operators {
    public static void main(String[] args) {
        //operators
        //multiplication
        int a = 20;
        int b = 30;
        int mul = a * b;
        System.out.println(mul);

        //Division
        int c = 20;
        int d = 30;
        int div = c / d;
        System.out.println(div);

        //Division
        double e = 20;
        double f = 30;
        double div1 = e / f;
        System.out.println(div1);
    }
}
